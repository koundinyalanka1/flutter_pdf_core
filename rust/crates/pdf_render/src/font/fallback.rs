/// One face as the generator hands it over.
pub struct BundledFace {
    pub name: String,
    pub serif: bool,
    pub coverage: Vec<(u32, u32)>,
    pub data: Vec<u8>,
}

struct BundleEntry {
    name: String,
    serif: bool,
    coverage: Vec<(u32, u32)>,
    offset: usize,
    length: usize,
}

/// Serialise faces into the format [`catalog`] reads: an index of names,
/// flags and coverage, then each face deflated on its own so that opening
/// Telugu never inflates Tibetan.
pub fn encode_bundle(faces: &[BundledFace]) -> Vec<u8> {
    let bodies: Vec<Vec<u8>> = faces
        .iter()
        .map(|face| pdf_core::filter::flate_encode(&face.data))
        .collect();
    let mut out = MAGIC.to_vec();
    put_varint(&mut out, faces.len() as u64);
    for (face, body) in faces.iter().zip(&bodies) {
        put_varint(&mut out, face.name.len() as u64);
        out.extend_from_slice(face.name.as_bytes());
        out.push(u8::from(face.serif));
        put_varint(&mut out, face.coverage.len() as u64);
        let mut next = 0u32;
        for &(lo, hi) in &face.coverage {
            put_varint(&mut out, u64::from(lo - next));
            put_varint(&mut out, u64::from(hi - lo));
            next = hi + 1;
        }
        put_varint(&mut out, body.len() as u64);
    }
    for body in bodies {
        out.extend_from_slice(&body);
    }
    out
}

fn bundle_index() -> &'static [BundleEntry] {
    static INDEX: OnceLock<Vec<BundleEntry>> = OnceLock::new();
    INDEX.get_or_init(|| {
        let Some(rest) = BUNDLE.strip_prefix(MAGIC.as_slice()) else {
            return Vec::new();
        };
        let mut at = 0usize;
        let varint = |at: &mut usize| -> Option<u64> {
            let mut value = 0u64;
            for shift in (0..64).step_by(7) {
                let byte = *rest.get(*at)?;
                *at += 1;
                value |= u64::from(byte & 0x7F) << shift;
                if byte & 0x80 == 0 {
                    return Some(value);
                }
            }
            None
        };
        let mut parse = || -> Option<Vec<BundleEntry>> {
            let count = varint(&mut at)? as usize;
            let mut entries = Vec::with_capacity(count);
            for _ in 0..count {
                let len = varint(&mut at)? as usize;
                let name = String::from_utf8(rest.get(at..at + len)?.to_vec()).ok()?;
                at += len;
                let serif = *rest.get(at)? == 1;
                at += 1;
                let ranges = varint(&mut at)? as usize;
                let mut coverage = Vec::with_capacity(ranges);
                let mut next = 0u32;
                for _ in 0..ranges {
                    let lo = next + varint(&mut at)? as u32;
                    let hi = lo + varint(&mut at)? as u32;
                    coverage.push((lo, hi));
                    next = hi + 1;
                }
                let length = varint(&mut at)? as usize;
                entries.push(BundleEntry {
                    name,
                    serif,
                    coverage,
                    offset: 0,
                    length,
                });
            }
            let mut offset = MAGIC.len() + at;
            for entry in &mut entries {
                entry.offset = offset;
                offset += entry.length;
            }
            Some(entries)
        };
        parse().unwrap_or_default()
    })
}

fn bundled_font(index: usize) -> Option<TrueTypeFont> {
    let entry = bundle_index().get(index)?;
    let compressed = BUNDLE.get(entry.offset..entry.offset + entry.length)?;
    TrueTypeFont::parse(pdf_core::filter::flate_decode(compressed).ok()?)
}

fn put_varint(out: &mut Vec<u8>, mut value: u64) {
    loop {
        let byte = (value & 0x7F) as u8;
        value >>= 7;
        if value == 0 {
            out.push(byte);
            return;
        }
        out.push(byte | 0x80);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn style(bold: bool, italic: bool, fixed_pitch: bool) -> FallbackStyle {
        FallbackStyle {
            bold,
            italic,
            fixed_pitch,
            serif: false,
        }
    }

    fn sans() -> FallbackFont {
        set_system_fonts_enabled(false);
        FallbackFont::for_style(style(false, false, false)).expect("fallback available")
    }

    #[test]
    fn embedded_faces_parse() {
        assert!(
            catalog().roboto(false).is_some(),
            "Roboto-Regular should parse"
        );
        assert!(catalog().roboto(true).is_some(), "Roboto-Bold should parse");
        assert!(bundle_index().len() >= 30, "the Noto bundle is present");
    }

    #[test]
    fn draws_latin_letters() {
        let font = sans();
        for ch in ['A', 'g', '7', '%'] {
            let outline = font.outline_for_char(ch).expect("outline should exist");
            assert!(!outline.is_empty(), "{ch} should have a non-empty outline");
        }
        // A space is a real glyph with no contours; that is not a failure.
        assert!(font.advance(' ').unwrap_or(0.0) > 0.0);
    }

    /// Characters Roboto lacks come from the bundled faces, on any device.
    #[test]
    fn draws_every_bundled_script() {
        let font = sans();
        for ch in [
            'క', 'क', 'ক', 'ਕ', 'ક', 'କ', 'க', 'ಕ', 'ക', 'ක', 'ก', 'ກ', 'ក', 'က', 'ཀ', 'ა', 'Ա',
            'ሀ', 'ބ', 'ܐ', 'ᠠ', 'ꀀ', 'Ꭰ', 'ᐁ', 'ⴰ', 'ߊ', 'ᱚ', 'ꯀ', 'ꦄ', '𞤀', 'א', 'ب', 'ɛ', '∮',
            '✓', '♞',
        ] {
            assert!(
                font.outline_for_char(ch).is_some(),
                "{ch} (U+{:04X}) should be drawable from the bundle",
                ch as u32
            );
        }
    }

    #[test]
    fn outlines_are_normalised_to_a_thousand_units() {
        let font = sans();
        // Roboto's em is 2048; a capital A is roughly 0.7 em tall.
        let (_, _, _, top) = font.outline_for_char('A').unwrap().bounds().unwrap();
        assert!((600.0..800.0).contains(&top), "cap height {top}");
        // Noto's em is 1000; its Telugu letters sit in the same range.
        let (_, _, _, top) = font.outline_for_char('క').unwrap().bounds().unwrap();
        assert!((400.0..1000.0).contains(&top), "Telugu height {top}");
    }

    #[test]
    fn style_detection_reads_subset_prefixed_names() {
        let s = FallbackStyle::detect("ABCDEF+Helvetica-BoldOblique", 0);
        assert!(s.bold && s.italic && !s.fixed_pitch && !s.serif);

        let s = FallbackStyle::detect("Times-Roman", 0);
        assert!(!s.bold && !s.italic && !s.fixed_pitch && s.serif);

        let s = FallbackStyle::detect("Courier", 0);
        assert!(s.fixed_pitch && !s.serif);

        // Descriptor flags stand in when the name says nothing.
        let s = FallbackStyle::detect("SomeFont", (1 << 18) | (1 << 6) | 2);
        assert!(s.bold && s.italic && s.serif);
    }

    #[test]
    fn courier_advances_are_monospaced() {
        set_system_fonts_enabled(false);
        let font = FallbackFont::for_style(style(false, false, true)).unwrap();
        assert_eq!(font.advance('i'), Some(600.0));
        assert_eq!(font.advance('W'), Some(600.0));
    }

    #[test]
    fn proportional_advances_differ_by_glyph() {
        let font = sans();
        let narrow = font.advance('i').unwrap();
        let wide = font.advance('W').unwrap();
        assert!(
            wide > narrow,
            "W ({wide}) should be wider than i ({narrow})"
        );
    }

    #[test]
    fn italic_shear_moves_upper_outline_right() {
        set_system_fonts_enabled(false);
        let upright = sans().outline_for_char('l').unwrap();
        let slanted = FallbackFont::for_style(style(false, true, false))
            .unwrap()
            .outline_for_char('l')
            .unwrap();
        let max_x = |p: &Path| p.bounds().expect("glyph has bounds").2;
        assert!(max_x(&slanted) > max_x(&upright));
    }

    #[test]
    fn regions_come_from_collections_and_font_names() {
        assert_eq!(
            CjkRegion::from_collection("Adobe-Japan1"),
            Some(CjkRegion::Japanese)
        );
        assert_eq!(
            CjkRegion::from_collection("Adobe-GB1"),
            Some(CjkRegion::SimplifiedChinese)
        );
        assert_eq!(CjkRegion::from_collection("Adobe-Identity"), None);
        assert_eq!(
            CjkRegion::from_font_name("MS-Mincho"),
            Some(CjkRegion::Japanese)
        );
        assert_eq!(
            CjkRegion::from_font_name("SimSun"),
            Some(CjkRegion::SimplifiedChinese)
        );
        assert_eq!(
            CjkRegion::from_font_name("MingLiU"),
            Some(CjkRegion::TraditionalChinese)
        );
        assert_eq!(CjkRegion::from_font_name("Batang"), Some(CjkRegion::Korean));
        assert_eq!(CjkRegion::from_font_name("Helvetica"), None);
    }

    #[test]
    fn placeholder_and_hidden_faces_never_stand_in() {
        let info = |family: &str, postscript: &str| FaceInfo {
            path: PathBuf::new(),
            index: 0,
            family: family.into(),
            postscript: postscript.into(),
            weight: 400,
            italic: false,
            serif: false,
            monospace: false,
            coverage: vec![(0, 0x10FFFF)],
        };
        assert!(!usable_system_face(&info(".LastResort", "LastResort")));
        assert!(!usable_system_face(&info(
            ".Apple SD Gothic NeoI",
            ".AppleSDGothicNeoI-Regular"
        )));
        assert!(!usable_system_face(&info(
            "Apple Color Emoji",
            "AppleColorEmoji"
        )));
        assert!(usable_system_face(&info(
            "Hiragino Sans",
            "HiraginoSans-W3"
        )));
    }

    #[test]
    fn han_prefers_the_documents_region() {
        let candidate = |names: &str| Candidate {
            source: Source::Roboto { bold: false },
            serif: false,
            bold: false,
            italic: false,
            monospace: false,
            names: names.into(),
            coverage: Vec::new(),
            loaded: OnceLock::new(),
        };
        let japanese = candidate(" hiragino sans hiraginosans-w3");
        let korean = candidate(" apple sd gothic neo applesdgothicneo-regular");
        let s = style(false, false, false);
        assert!(
            score(&japanese, s, Some(CjkRegion::Japanese))
                > score(&korean, s, Some(CjkRegion::Japanese))
        );
        assert!(
            score(&korean, s, Some(CjkRegion::Korean))
                > score(&japanese, s, Some(CjkRegion::Korean))
        );
        assert_eq!(cjk_need('中'), Some(None));
        assert_eq!(cjk_need('あ'), Some(Some(CjkRegion::Japanese)));
        assert_eq!(cjk_need('한'), Some(Some(CjkRegion::Korean)));
        assert_eq!(cjk_need('A'), None);
    }
}
