const ROBOTO_REGULAR: &[u8] = include_bytes!("../../fonts/Roboto-Regular.ttf");
const ROBOTO_BOLD: &[u8] = include_bytes!("../../fonts/Roboto-Bold.ttf");

/// The bundled Noto faces, generated by the `build_fallback_bundle` example.
static BUNDLE: &[u8] = include_bytes!("../../data/fallback-fonts.bin");
const MAGIC: &[u8; 8] = b"PDFFONT1";

/// How much to lean a synthesised italic, as a shear on x per unit y.
/// 0.21 is about 12 degrees, the slope most oblique faces use.
const OBLIQUE_SHEAR: f64 = 0.21;

/// Outlines and advances come back in this many units per em.
const UNITS: f64 = 1000.0;

static SYSTEM_FONTS: AtomicBool = AtomicBool::new(true);
static EXTRA_DIRECTORIES: Mutex<Vec<PathBuf>> = Mutex::new(Vec::new());

/// Whether installed fonts may be used. Off makes rendering depend only on
/// what ships in the library — reproducible across machines, for tests.
pub fn set_system_fonts_enabled(enabled: bool) {
    SYSTEM_FONTS.store(enabled, Ordering::Relaxed);
}

/// Another directory to look for installed fonts in, such as fonts an app
/// ships or downloads itself. Takes effect if added before the first lookup
/// that needs installed fonts.
pub fn add_font_directory(path: impl Into<PathBuf>) {
    if let Ok(mut dirs) = EXTRA_DIRECTORIES.lock() {
        dirs.push(path.into());
    }
}

/// Which substitute face a font dictionary should borrow.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct FallbackStyle {
    pub bold: bool,
    pub italic: bool,
    /// Courier and friends: every glyph advances 600/1000 em.
    pub fixed_pitch: bool,
    /// Times, Mincho, Song: a design with serifs.
    pub serif: bool,
}

impl FallbackStyle {
    /// Read weight and slope out of a `/BaseFont` name and the descriptor
    /// flags. Names look like `AAAAAA+Helvetica-BoldOblique`, and the style
    /// words are the only part worth trusting.
    pub fn detect(base_font: &str, flags: i64) -> FallbackStyle {
        let name = base_font.to_ascii_lowercase();
        let bold = name.contains("bold")
            || name.contains("black")
            || name.contains("heavy")
            || name.contains("semibold")
            // Bit 19 (1 << 18) is ForceBold.
            || flags & (1 << 18) != 0;
        let italic = name.contains("italic")
            || name.contains("oblique")
            // Bit 7 (1 << 6) is Italic.
            || flags & (1 << 6) != 0;
        let fixed_pitch = name.contains("courier")
            || name.contains("mono")
            // Bit 1 is FixedPitch.
            || flags & 1 != 0;
        // Bit 2 is Serif; the name decides when the flags are silent.
        let serif = !fixed_pitch && (flags & 2 != 0 || system::looks_serif(&name));
        FallbackStyle {
            bold,
            italic,
            fixed_pitch,
            serif,
        }
    }
}

