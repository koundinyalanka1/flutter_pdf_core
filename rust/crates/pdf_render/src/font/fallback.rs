/// A substitute for one non-embedded font.
pub struct FallbackFont {
    style: FallbackStyle,
    region: Option<CjkRegion>,
}

impl FallbackFont {
    pub fn for_style(style: FallbackStyle) -> Option<FallbackFont> {
        // Roboto always exists; whether a given character can be drawn is
        // decided per character.
        catalog().roboto(style.bold)?;
        Some(FallbackFont {
            style,
            region: None,
        })
    }

    /// Prefer this region's faces for Han characters.
    pub fn with_region(mut self, region: Option<CjkRegion>) -> FallbackFont {
        self.region = region;
        self
    }

    pub fn units_per_em(&self) -> f64 {
        UNITS
    }

    /// Outline for a Unicode character, sheared when a slanted face was asked
    /// for and the face that drew it is upright. `None` when no face has it.
    pub fn outline_for_char(&self, ch: char) -> Option<Path> {
        let (face, gid) = catalog().resolve(ch, self.style, self.region)?;
        let outline = face.font.glyph_outline(gid)?;
        let scale = UNITS / face.font.units_per_em;
        let mut matrix = Matrix::scale(scale, scale);
        if self.style.italic && !face.italic {
            matrix = matrix.then(&Matrix::new(1.0, 0.0, OBLIQUE_SHEAR, 1.0, 0.0, 0.0));
        }
        Some(outline.transform(&matrix))
    }

    /// Advance for a character, in text-space units (em/1000), for use only
    /// when the PDF gave no width of its own.
    pub fn advance(&self, ch: char) -> Option<f64> {
        if self.style.fixed_pitch {
            return Some(600.0);
        }
        let (face, gid) = catalog().resolve(ch, self.style, self.region)?;
        let upem = face.font.units_per_em;
        if upem <= 0.0 {
            return None;
        }
        Some(face.font.advance(gid)? * UNITS / upem)
    }
}

