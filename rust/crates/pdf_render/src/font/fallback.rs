fn catalog() -> &'static Catalog {
    static CATALOG: OnceLock<Catalog> = OnceLock::new();
    CATALOG.get_or_init(|| {
        let roboto = |bold: bool| {
            let data = if bold { ROBOTO_BOLD } else { ROBOTO_REGULAR };
            Candidate {
                source: Source::Roboto { bold },
                serif: false,
                bold,
                italic: false,
                monospace: false,
                names: "roboto".into(),
                coverage: sfnt_coverage(data),
                loaded: OnceLock::new(),
            }
        };
        let bundled = bundle_index()
            .iter()
            .enumerate()
            .map(|(index, entry)| Candidate {
                source: Source::Bundled { index },
                serif: entry.serif,
                bold: false,
                italic: false,
                monospace: false,
                names: entry.name.to_ascii_lowercase(),
                coverage: entry.coverage.clone(),
                loaded: OnceLock::new(),
            })
            .collect();
        Catalog {
            roboto: [roboto(false), roboto(true)],
            bundled,
            latin: OnceLock::new(),
            system: OnceLock::new(),
            memo: Mutex::new(HashMap::new()),
        }
    })
}

fn system_candidate(info: FaceInfo) -> Candidate {
    Candidate {
        serif: info.serif,
        bold: info.weight >= 600,
        italic: info.italic,
        monospace: info.monospace,
        names: format!(" {} {}", info.family, info.postscript).to_ascii_lowercase(),
        coverage: info.coverage.clone(),
        source: Source::System(info),
        loaded: OnceLock::new(),
    }
}

impl Catalog {
    fn roboto(&self, bold: bool) -> Option<Arc<Face>> {
        self.roboto[usize::from(bold)].face()
    }

    fn latin(&self) -> &[Candidate] {
        self.latin.get_or_init(|| {
            if !SYSTEM_FONTS.load(Ordering::Relaxed) {
                return Vec::new();
            }
            LATIN_FACES
                .iter()
                .map(std::path::Path::new)
                .filter(|path| path.is_file())
                .flat_map(system::scan_file)
                .filter(usable_system_face)
                .map(system_candidate)
                .collect()
        })
    }

    fn system(&self) -> &[Candidate] {
        self.system.get_or_init(|| {
            if !SYSTEM_FONTS.load(Ordering::Relaxed) {
                return Vec::new();
            }
            let mut dirs = system::default_directories();
            if let Ok(extra) = EXTRA_DIRECTORIES.lock() {
                dirs.extend(extra.iter().cloned());
            }
            system::scan(&dirs)
                .into_iter()
                .filter(usable_system_face)
                .map(system_candidate)
                .collect()
        })
    }

    fn candidate(&self, pick: Pick) -> Option<&Candidate> {
        match pick {
            Pick::Roboto(bold) => Some(&self.roboto[usize::from(bold)]),
            Pick::Bundled(index) => self.bundled.get(index),
            Pick::Latin(index) => self.latin().get(index),
            Pick::System(index) => self.system().get(index),
        }
    }

    /// The best-matching serif or monospace Latin face at a known path.
    fn styled_latin(&self, ch: char, style: FallbackStyle) -> Option<(Pick, Arc<Face>, u16)> {
        let code = ch as u32;
        let mut ranked: Vec<(i64, usize)> = self
            .latin()
            .iter()
            .enumerate()
            .filter(|(_, c)| c.covers(code))
            .filter(|(_, c)| {
                (style.fixed_pitch && c.monospace) || (style.serif && c.serif && !c.monospace)
            })
            .map(|(index, c)| (score(c, style, None), index))
            .collect();
        ranked.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
        ranked.into_iter().find_map(|(_, index)| {
            let (face, gid) = self.latin()[index].glyph(ch)?;
            Some((Pick::Latin(index), face, gid))
        })
    }

    fn resolve(
        &self,
        ch: char,
        style: FallbackStyle,
        region: Option<CjkRegion>,
    ) -> Option<(Arc<Face>, u16)> {
        let key = (ch, style, region);
        if let Some(found) = self
            .memo
            .lock()
            .ok()
            .and_then(|memo| memo.get(&key).copied())
        {
            return found.and_then(|(pick, gid)| Some((self.candidate(pick)?.face()?, gid)));
        }
        let found = self.search(ch, style, region);
        if let Ok(mut memo) = self.memo.lock() {
            memo.insert(key, found.as_ref().map(|(pick, _, gid)| (*pick, *gid)));
        }
        found.map(|(_, face, gid)| (face, gid))
    }

    fn search(
        &self,
        ch: char,
        style: FallbackStyle,
        region: Option<CjkRegion>,
    ) -> Option<(Pick, Arc<Face>, u16)> {
        let code = ch as u32;
        let roboto = &self.roboto[usize::from(style.bold)];

        // 1. Latin in the original's style: a serif or monospace design needs
        //    an installed face to look anything like it; sans is Roboto.
        if roboto.covers(code) && (style.serif || style.fixed_pitch) {
            if let Some(found) = self.styled_latin(ch, style) {
                return Some(found);
            }
        }
        if roboto.covers(code) {
            if let Some((face, gid)) = roboto.glyph(ch) {
                return Some((Pick::Roboto(style.bold), face, gid));
            }
        }
        // 2. Bundled scripts, symbols and mathematics.
        for (index, candidate) in self.bundled.iter().enumerate() {
            if candidate.covers(code) {
                if let Some((face, gid)) = candidate.glyph(ch) {
                    return Some((Pick::Bundled(index), face, gid));
                }
            }
        }
        // 3. Installed fonts.
        self.best_system(ch, style, region)
    }

    /// The best installed face for `ch`: the document's CJK region first for
    /// Han, kana and hangul, then the closest design.
    fn best_system(
        &self,
        ch: char,
        style: FallbackStyle,
        region: Option<CjkRegion>,
    ) -> Option<(Pick, Arc<Face>, u16)> {
        let code = ch as u32;
        let han_region =
            cjk_need(ch).map(|need| need.unwrap_or(region.unwrap_or(CjkRegion::SimplifiedChinese)));
        let mut ranked: Vec<(i64, usize)> = self
            .system()
            .iter()
            .enumerate()
            .filter(|(_, c)| c.covers(code))
            .map(|(index, c)| (score(c, style, han_region), index))
            .collect();
        ranked.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
        for (_, index) in ranked.into_iter().take(8) {
            if let Some((face, gid)) = self.system()[index].glyph(ch) {
                return Some((Pick::System(index), face, gid));
            }
        }
        None
    }
}

/// For a character that is Han, kana or hangul, the region it belongs to
/// (`Some(None)` for Han, which every region shares).
fn cjk_need(ch: char) -> Option<Option<CjkRegion>> {
    match ch as u32 {
        0x3040..=0x30FF | 0x31F0..=0x31FF | 0xFF66..=0xFF9F => Some(Some(CjkRegion::Japanese)),
        0x1100..=0x11FF | 0x3130..=0x318F | 0xA960..=0xA97F | 0xAC00..=0xD7AF | 0xD7B0..=0xD7FF => {
            Some(Some(CjkRegion::Korean))
        }
        0x2E80..=0x2FDF
        | 0x3000..=0x303F
        | 0x3400..=0x4DBF
        | 0x4E00..=0x9FFF
        | 0xF900..=0xFAFF
        | 0xFF00..=0xFF65
        | 0x20000..=0x3FFFF => Some(None),
        _ => None,
    }
}

/// How well an installed face suits a character in a given style.
fn score(c: &Candidate, style: FallbackStyle, region: Option<CjkRegion>) -> i64 {
    let mut score = 0;
    if let Some(region) = region {
        if region.font_words().iter().any(|w| c.names.contains(w)) {
            score += 100;
        }
    }
    if c.serif == style.serif {
        score += 20;
    }
    if c.monospace == style.fixed_pitch {
        score += 10;
    }
    if c.bold == style.bold {
        score += 8;
    }
    if c.italic == style.italic {
        score += 4;
    }
    // User-interface variants have odd metrics for running text.
    if c.names.contains("interface") || c.names.contains(" ui") {
        score -= 30;
    }
    score
}

/// Installed faces that must never stand in: Apple's hidden system faces
/// (names starting with a dot), the LastResort placeholder font that "covers"
/// every character with a box naming its block, and emoji faces.
fn usable_system_face(info: &FaceInfo) -> bool {
    let family = info.family.trim();
    let lower = format!("{} {}", info.family, info.postscript).to_ascii_lowercase();
    !family.is_empty()
        && !family.starts_with('.')
        && !info.postscript.starts_with('.')
        && !lower.contains("lastresort")
        && !lower.contains("emoji")
}

/// A single-face font's coverage, read through its own cmap.
fn sfnt_coverage(data: &[u8]) -> Vec<(u32, u32)> {
    TrueTypeFont::parse(data.to_vec())
        .map(|font| font.coverage())
        .unwrap_or_default()
}

