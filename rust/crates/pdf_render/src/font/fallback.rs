/// A face, loaded.
struct Face {
    font: TrueTypeFont,
    italic: bool,
}

/// Where a candidate face comes from.
enum Source {
    Roboto { bold: bool },
    Bundled { index: usize },
    System(FaceInfo),
}

/// A face that might draw a character: what it covers and looks like, and
/// the face itself once something asked for it.
struct Candidate {
    source: Source,
    serif: bool,
    bold: bool,
    italic: bool,
    monospace: bool,
    /// Family and PostScript names, lowercased, for region matching.
    names: String,
    coverage: Vec<(u32, u32)>,
    loaded: OnceLock<Option<Arc<Face>>>,
}

impl Candidate {
    fn covers(&self, ch: u32) -> bool {
        let index = self.coverage.partition_point(|&(lo, _)| lo <= ch);
        index > 0 && ch <= self.coverage[index - 1].1
    }

    fn face(&self) -> Option<Arc<Face>> {
        self.loaded
            .get_or_init(|| {
                let font = match &self.source {
                    Source::Roboto { bold } => TrueTypeFont::parse(
                        if *bold { ROBOTO_BOLD } else { ROBOTO_REGULAR }.to_vec(),
                    ),
                    Source::Bundled { index } => bundled_font(*index),
                    Source::System(info) => system::load_face(&info.path, info.index),
                }?;
                font.has_outlines().then(|| {
                    Arc::new(Face {
                        font,
                        italic: self.italic,
                    })
                })
            })
            .clone()
    }

    /// The glyph for `ch`, when the face really has an outline for it — a
    /// cmap entry pointing at an empty or bitmap-only glyph does not count.
    fn glyph(&self, ch: char) -> Option<(Arc<Face>, u16)> {
        let face = self.face()?;
        let gid = face.font.glyph_for_char(ch as u32)?;
        if gid == 0 {
            return None;
        }
        if !ch.is_whitespace() && face.font.glyph_outline(gid).is_none() {
            return None;
        }
        Some((face, gid))
    }
}

/// Which candidate drew a character, remembered per style and region.
#[derive(Clone, Copy)]
enum Pick {
    Roboto(bool),
    Bundled(usize),
    Latin(usize),
    System(usize),
}

struct Catalog {
    roboto: [Candidate; 2],
    bundled: Vec<Candidate>,
    /// Serif and monospace Latin faces at well-known paths, checked without
    /// a full scan: the standard Times and Courier are too common to make
    /// their first page wait on indexing every installed font.
    latin: OnceLock<Vec<Candidate>>,
    system: OnceLock<Vec<Candidate>>,
    memo: Mutex<HashMap<MemoKey, Option<(Pick, u16)>>>,
}

/// A character in a style and region, for remembering which face drew it.
type MemoKey = (char, FallbackStyle, Option<CjkRegion>);

