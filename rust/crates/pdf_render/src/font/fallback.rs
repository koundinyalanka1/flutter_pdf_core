//! Substitute outlines for fonts a PDF does not embed — in every script.
//!
//! A PDF may name any of the 14 standard fonts, or any installed font, and
//! embed nothing; or embed a program this renderer cannot read. Drawing
//! nothing turned such documents into blank pages, and drawing only Roboto
//! left every non-Latin character blank. The document's own `/Widths` still
//! place each glyph, so a substitute only has to supply shapes.
//!
//! A character is looked for, in order, in:
//!
//! 1. a Latin face matched to the original's style — the device's own serif
//!    or monospace face for Times or Courier, Roboto otherwise;
//! 2. the bundled Noto faces (`data/fallback-fonts.bin`), which cover the
//!    scripts of living languages, mathematics and symbols on every device;
//! 3. the device's installed fonts (see [`super::system`]), which is where
//!    Chinese, Japanese and Korean come from: every phone and desktop ships
//!    a CJK face, and bundling one would add twenty megabytes. Han
//!    characters prefer a face for the document's own region, since the
//!    same code point is drawn differently in Japan, China and Korea.
//!
//! Outlines are returned in 1000 units per em whatever the face's own em,
//! because one substituted font may borrow glyphs from several faces.

